/**
 * Calculates standard unit price (per KG / per Liter / per Packet / per Piece)
 * from a quoted rate and unit.
 */
export function calculateStandardUnitPrice(
  quotedPrice: number,
  quotedUnit: QuoteUnitType
): { standardUnit: UnitType; standardUnitPrice: number } {
  switch (quotedUnit) {
    case '১০০ গ্রাম':
      return { standardUnit: 'কেজি', standardUnitPrice: Math.round(quotedPrice * 10) };
    case '২৫০ গ্রাম':
      return { standardUnit: 'কেজি', standardUnitPrice: Math.round(quotedPrice * 4) };
    case 'গ্রাম':
      return { standardUnit: 'কেজি', standardUnitPrice: Math.round(quotedPrice * 1000) };
    case 'লিটার':
      return { standardUnit: 'লিটার', standardUnitPrice: quotedPrice };
    case 'প্যাকেট':
      return { standardUnit: 'প্যাকেট', standardUnitPrice: quotedPrice };
    case 'বোতল':
    case 'পিস':
      return { standardUnit: 'পিস', standardUnitPrice: quotedPrice };
    case 'কেজি':
    default:
      return { standardUnit: 'কেজি', standardUnitPrice: quotedPrice };
  }
}

